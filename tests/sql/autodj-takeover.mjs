import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';

// Disposable PostgreSQL only. Uses the migration, never the venue database.
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema jukebox_private;
    create function jukebox_private.secret_ok() returns boolean language sql stable as $$
      select coalesce(current_setting('request.headers', true), '{}')::jsonb->>'x-jukebox-secret' = 'test-only'
    $$;
    create table jukebox_private.queue (
      id bigint generated by default as identity primary key,
      video_id text not null, title text not null, artist text not null default '',
      thumbnail text not null default '', requested_by text not null default '', requester_id text not null,
      status text not null default 'queued', priority integer not null default 0, votes integer not null default 0,
      priority_requested boolean not null default false, created_at bigint not null default 0,
      started_at bigint, finished_at bigint,
      check(status in ('playing','queued','done','removed')),
      check(priority >= 0 or (requester_id='autodj' and priority=-100))
    );
    create unique index queue_active_video on jukebox_private.queue(video_id) where status in ('playing','queued');
    create unique index queue_one_playing on jukebox_private.queue((status)) where status='playing';
    create table jukebox_private.votes(queue_id bigint, voter_id text, created_at bigint, unique(queue_id,voter_id));
    create table jukebox_private.player_state (
      id integer primary key, revision bigint not null default 0,
      action text not null default 'sync', updated_at bigint not null default 0,
      volume integer not null default 80, night_mode boolean not null default false
    );
    insert into jukebox_private.player_state(id) values(1);
    alter table jukebox_private.queue enable row level security;
    alter table jukebox_private.votes enable row level security;
    alter table jukebox_private.player_state enable row level security;
    create policy backend_queue on jukebox_private.queue to anon using(jukebox_private.secret_ok()) with check(jukebox_private.secret_ok());
    create policy backend_votes on jukebox_private.votes to anon using(jukebox_private.secret_ok()) with check(jukebox_private.secret_ok());
    create policy backend_player on jukebox_private.player_state to anon using(jukebox_private.secret_ok()) with check(jukebox_private.secret_ok());
    grant usage on schema jukebox_private to anon;
    grant select, insert, update on jukebox_private.queue, jukebox_private.votes, jukebox_private.player_state to anon;
    grant usage on all sequences in schema jukebox_private to anon;
  `);
  const migrations = new URL('../../supabase/migrations/', import.meta.url);
  for (const suffix of ['_autodj_guest_takeover_and_history.sql', '_add_guest_skip_own_song.sql', '_add_idempotent_player_transition.sql']) {
    const file = fs.readdirSync(migrations).find(name => name.endsWith(suffix));
    await db.exec(fs.readFileSync(new URL(file, migrations), 'utf8'));
  }
  const rpc = async (action, payload = {}, name = 'jukebox_rpc') => (await db.query(
    `select public.${name}($1, $2::jsonb) as result`, [action, JSON.stringify(payload)],
  )).rows[0].result;
  const add = (video_id, requester_id = 'guest-a', extra = {}) => rpc('add_song', {
    video_id, title: 'Party guest', requester_id, interrupt_autodj: true, ...extra,
  });
  const queue = async () => (await db.query('select id,video_id,status,requester_id from jukebox_private.queue order by id')).rows;
  const player = () => rpc('player_state');
  await db.exec("set role anon; set request.headers = '{}';");
  assert.equal((await add('A1234567890'))._status, 401, 'null secret result cannot authorize');
  assert.equal((await rpc('status', {}, 'jukebox_autodj_rpc'))._status, 401);
  await db.exec(`set request.headers = '{"x-jukebox-secret":"test-only"}';`);
  await db.exec(`insert into jukebox_private.queue(video_id,title,requester_id,requested_by,priority,status)
    values('Z1234567890','Auto','autodj','AutoDJ · Funk',-100,'playing');`);
  const original = await queue();
  assert.equal((await add('invalid'))._status, 422);
  assert.equal((await add('Z1234567890'))._status, 409);
  assert.deepEqual(await queue(), original, 'failed additions cannot interrupt AutoDJ');
  const first = await add('A1234567890');
  assert.equal(first.status, 'playing');
  assert.equal(first.requested_by_me, true);
  assert.equal('requester_id' in first, false);
  assert.equal((await queue())[0].status, 'done');
  assert.equal((await player()).action, 'guest_takeover');
  assert.equal((await player()).now_playing.is_autodj, false);
  const second = await add('B1234567890', 'guest-b');
  assert.equal(second.status, 'queued', 'another guest cannot interrupt the owner');
  assert.equal((await player()).now_playing.id, first.id);
  const skipped = await rpc('skip', {song_id: first.id, requester_id: 'guest-a'}, 'jukebox_guest_skip_rpc');
  assert.deepEqual(skipped, {ok: true, idempotent: false});
  assert.equal((await player()).now_playing.id, second.id);
  await rpc('skip', {song_id: first.id, requester_id: 'guest-a'}, 'jukebox_guest_skip_rpc');
  assert.equal((await player()).now_playing.id, second.id, 'late guest skip preserves the new song');

  await db.exec(`reset role; delete from jukebox_private.queue; update jukebox_private.player_state set revision=0;
    insert into jukebox_private.queue(video_id,title,requester_id,priority,status) values
      ('Z1234567890','Auto','autodj',-100,'playing'),
      ('C1234567890','Earlier guest','guest-c',0,'queued'); set role anon;`);
  const later = await add('D1234567890');
  assert.equal(later.status, 'queued');
  assert.equal((await player()).now_playing.video_id, 'C1234567890', 'takeover respects existing queue order');
  const stale = await rpc('transition', {current_song_id: (await queue())[0].id, next_song_id: later.id}, 'jukebox_transition_rpc');
  assert.equal(stale._status, 409);
  assert.equal((await player()).now_playing.video_id, 'C1234567890', 'late AutoDJ transition cannot replace a guest');

  await db.exec(`reset role; delete from jukebox_private.queue;
    create function jukebox_private.fail_player_update() returns trigger language plpgsql as $$ begin raise exception 'test write failure'; end $$;
    create trigger fail_player before update on jukebox_private.player_state for each row execute function jukebox_private.fail_player_update();
    insert into jukebox_private.queue(video_id,title,requester_id,priority,status)
      values('Z1234567890','Auto','autodj',-100,'playing'); set role anon;`);
  const beforeFailure = await queue();
  await assert.rejects(add('A1234567890'), /test write failure/);
  assert.deepEqual(await queue(), beforeFailure, 'takeover insertion and player changes roll back together');
  await db.exec(`reset role; drop trigger fail_player on jukebox_private.player_state; delete from jukebox_private.queue; set role anon;`);
  const ids = [...'ABCDEFGHIJ'].map(letter => `${letter}1234567890`);
  for (const video_id of ids) {
    const prepared = await rpc('prepare', {video_id, title: 'Upbeat groove'}, 'jukebox_autodj_rpc');
    assert.equal(prepared.prepared, true);
    await rpc('player_start');
    await rpc('player_ended');
  }
  const history = await rpc('status', {}, 'jukebox_autodj_rpc');
  assert.deepEqual(new Set(history.recent_video_ids), new Set(ids));
  assert.deepEqual(await rpc('prepare', {video_id: ids[0], title: 'Repeat'}, 'jukebox_autodj_rpc'), {prepared: false, reason: 'recent'});
  const liveGuest = await add('K1234567890');
  assert.deepEqual(await rpc('prepare', {video_id: liveGuest.video_id, title: 'Duplicate'}, 'jukebox_autodj_rpc'), {prepared: false, reason: 'recent'});
  await db.exec('reset role;');
  const flags = (await db.query(`select proname, prosecdef,
    has_function_privilege('authenticated', oid, 'execute') as authenticated_access
    from pg_proc where proname in ('jukebox_rpc','jukebox_autodj_rpc')`)).rows;
  assert.equal(flags.length, 2);
  assert.ok(flags.every(f => !f.prosecdef && !f.authenticated_access));
  console.log('PostgreSQL AutoDJ: secret/RLS, atomic takeover, queue order, guest skip, late transitions, rollback and history beyond six verified.');
} finally { await db.close(); }
